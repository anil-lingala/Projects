def extract_features(url):
    features = {}

    # contain https (1 if yes; 0 if no )
    features['has_https'] = 1 if url.startswith('https') else 0

    # @ symbol
    features['has_at_symbol'] = 1 if '@' in url else 0

    # contains ip
    features['has_ip_address'] = 1 if re.search(r'\d+\.\d+\.\d+\.\d+', url) else 0

    # contains suspicious keywords
    suspicious_words = ['login', 'verify', 'update', 'secure', 'banking', 'confirm', 'password', 'account']
    features['has_suspicious_words'] = 1 if any(word in url.lower() for word in suspicious_words) else 0

    # url length
    features['url_length'] = len(url)

    #check if the domain is trying to impersonate a trusted site
    domain = re.sub(r'https?://', '', url).split('/')[0]
    features['is_lookalike'] = 0
    for trusted in trusted_domains:
        distance = Levenshtein.distance(domain, trusted)
        if distance <= 2 and domain != trusted:
            features['is_lookalike'] = 1
            break

    # more dots usually means more subdomains which is suspicious
    features['num_dots'] = url.count('.')

    # dashes
    features['num_dashes'] = url.count('-')

    # subdomains
    domain = re.sub(r'https?://', '', url).split('/')[0]
    features['num_subdomains'] = len(domain.split('.')) - 1

    # special chars
    features['num_special_chars'] = len(re.findall(r'[^a-zA-Z0-9]', url))

    # how many digits
    features['num_digits'] = len(re.findall(r'\d', url))

    # check if URL has a port number in it
    features['has_port'] = 1 if re.search(r':\d+', url) else 0

    # measure randomness of the URL - phishing URLs tend to have high entropy
    import math
    prob = [float(url.count(c)) / len(url) for c in set(url)]
    features['entropy'] = -sum(p * math.log(p, 2) for p in prob)

    return features

