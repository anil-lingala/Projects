def normalize_url(url):
    # Remove spaces before and after the URL.
    url = url.strip()

    # Add https:// if the user did not enter it.
    if not re.match(r"^https?://", url, re.IGNORECASE):
        url = "https://" + url

    parsed = urlparse(url)

    # Accept only HTTP or HTTPS URLs with a domain.
    if parsed.scheme.lower() not in ["http", "https"]:
        raise ValueError("Only HTTP or HTTPS URLs are allowed.")

    if not parsed.netloc:
        raise ValueError("The URL does not contain a valid domain.")

    # Rebuild the URL without the fragment section.
    return urlunparse(
        (
            parsed.scheme.lower(),
            parsed.netloc,
            parsed.path or "/",
            parsed.params,
            parsed.query,
            "",
        )
    )


def google_error(status, message):
    return {
        "status": status,
        "message": message,
        "is_threat": False,
        "threat_types": [],
    }


def check_google_safe_browsing(url):
    api_key = os.getenv("GOOGLE_SAFE_BROWSING_API_KEY", "").strip()

    if not api_key:
        return google_error(
            "missing_key",
            "API Key is missing"
        )

    try:
        clean_url = normalize_url(url)
    except ValueError as error:
        return google_error(
            "invalid_url",
            str(error),
        )

    request_body = {
        "client": {
            "clientId": "cs6301-url-detector",
            "clientVersion": "1.0",
        },
        "threatInfo": {
            "threatTypes": [
                "MALWARE",
                "SOCIAL_ENGINEERING",
                "UNWANTED_SOFTWARE",
                "POTENTIALLY_HARMFUL_APPLICATION",
            ],
            "platformTypes": ["ANY_PLATFORM"],
            "threatEntryTypes": ["URL"],
            "threatEntries": [
                {"url": clean_url}
            ],
        },
    }

    try:
        response = requests.post(
            GOOGLE_API_URL,
            params={"key": api_key},
            json=request_body,
            timeout=10,
        )

        if response.status_code in [400, 401, 403]:
            return google_error(
                "authentication_error",
                "Check the API key and Settings",
            )

        if response.status_code == 429:
            return google_error(
                "quota_exceeded",
                "The google API quita was exceeded",
            )

        response.raise_for_status()

        data = response.json()
        threats = data.get("matches", [])

        threat_types = []

        for threat in threats:
            threat_type = threat.get("threatType")

            if threat_type and threat_type not in threat_types:
                threat_types.append(threat_type)

        return {
            "status": "ok",
            "message": "Google Safe Browsing check completed.",
            "is_threat": len(threats) > 0,
            "threat_types": threat_types,
        }

    except requests.Timeout:
        return google_error(
            "timeout",
            "The Google request timed out.",
        )

    except requests.RequestException:
        return google_error(
            "request error",
            "The Google request failed.",
        )

    except ValueError:
        return google_error(
            "response error",
            "Google returned an invalid response.",
        )

